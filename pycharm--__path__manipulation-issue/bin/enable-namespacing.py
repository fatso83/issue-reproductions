#!/usr/bin/env python
"""
enable-namespacing
------------------

The esslib project makes extensive use of namespaced packages.

What this means is that a given module foo.bar.baz can reside under
the physical locations of pkg-a/foo/bar or pkg-b/foo/bar.

This happens by expanding the "magic" variable `__path__`, which is
a list of paths that the runtime will look when trying to locate modules
within a given package. Usually, this list has a single element, but
by adding multiple locations you can achieve quazi-namespacing.

The pkgutil.extend_path(path,name) utility will search the system path (PYTHONPATH)
for packages with identical _name_ and expand _path_ to include all of these.

We basically had two choices:
    1. Manually add all package locations under esslib into the system path
    and invoke pkgutil.extend_path(path,name). This was the approach up until
    recently, but required manual fiddling with the PYTHONPATH, which is
    incompatible when the library is packaged and consumed by a third-party.
    2. Re-create the top-level package structure and add all the sibling
    packages to the search path programmatically.

This script takes the second approach, as fiddling with PYTHONPATH
does not work well with packaging for consumption. Additionally, by
including it into a direnv file, we can avoid manual invocations to
keep the structure in-sync with the actual package layout as it changes.

Re-running has no side-effects, apart from recreation of any missing dirs
"""

import os
from pathlib import Path
from typing import Dict, List, Set

PROJECT_ROOT = (
    Path(__file__).resolve().parent.parent
)  # assuming the script lives in ./bin
SEARCH_ROOT = Path(PROJECT_ROOT, "subdir").resolve()
OUT_PARENT = Path(PROJECT_ROOT, "subdir").resolve()  # where ../<name>/__init__.py lives
MAX_DEPTH = 4

AUTOGENERATED_TEXT = """
##############################################################
# AUTOGENERATED - DO NOT ADD OR EDIT FILES IN THIS DIRECTORY
# AS CHANGES WILL BE OVERWRITTEN!
#
# See bin/enable-namespacing.py for additional documentation
##############################################################
"""


def find_python_roots(base: Path) -> List[Path]:
    roots = []
    for root, dirs, _ in os.walk(base):
        rel = os.path.relpath(root, base)
        depth = 0 if rel == "." else rel.count(os.sep) + 1
        if depth > MAX_DEPTH:
            dirs[:] = []
            continue
        if os.path.basename(root) == "python":
            roots.append(Path(root).resolve())
        if os.path.basename(root) == "rfw":
            roots.append(Path(root).resolve())
    return roots


def collect_top_packages(pyroots: List[Path]) -> Dict[str, Set[Path]]:
    by_name: Dict[str, Set[Path]] = {}
    for root in pyroots:
        for entry in os.scandir(root):
            if entry.is_dir() and entry.name != "__pycache__":
                by_name.setdefault(entry.name, set()).add(root)
    return by_name


INIT_TPL = """{autogenerated_text}

from lib_utils.namespace import extend_namespace
extend_namespace(__file__, __path__, __name__, [{rel_list}])
"""


def write_init_for(name: str, pyroots: Set[Path]):
    pkg_dir = OUT_PARENT / name
    pkg_dir.mkdir(parents=True, exist_ok=True)
    init_py = pkg_dir / "__init__.py"
    warning_file = pkg_dir / "AUTOGENERATED.txt"

    # compute rel paths from the package dir to each python root
    rels = []
    for r in sorted(pyroots):
        rel = os.path.relpath(r, pkg_dir)
        rels.append(f'    "{rel.replace(os.sep, "/")}",')

    content = INIT_TPL.format(
        rel_list="\n".join(rels), autogenerated_text=AUTOGENERATED_TEXT
    )
    init_py.write_text(content, encoding="utf-8")

    warning_file.write_text(
        AUTOGENERATED_TEXT,
        encoding="utf-8",
    )


def build():
    pyroots = find_python_roots(SEARCH_ROOT)
    by_name = collect_top_packages(pyroots)
    for name, roots in by_name.items():
        write_init_for(name, roots)


if __name__ == "__main__":
    build()
